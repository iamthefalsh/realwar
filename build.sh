#!/bin/sh
# Builds both targets from src/:
#   index.html          the single-file game (Vercel serves this)
#   server/src/sim.js   the same game rules, headless, for the multiplayer server
set -e
cd "$(dirname "$0")/src"
cat head.html data.js map.js game.js econ.js ai.js commands.js render.js art.js mp.js ui.js tail.html > ../index.html
{
  echo "// GENERATED by build.sh from src/ - do not edit by hand."
  echo "// Each call creates an isolated copy of the game, so many matches can share one server."
  echo "export function createSim(){"
  echo "'use strict';"
  cat data.js map.js game.js econ.js ai.js commands.js server-shim.js
  echo "}"
} > ../server/src/sim.js
echo "built index.html ($(wc -c < ../index.html) bytes) and server/src/sim.js ($(wc -c < ../server/src/sim.js) bytes)"
